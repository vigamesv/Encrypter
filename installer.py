def detect_system():
    """Identify the current OS (and, on Linux, the distro family) and how to
    get missing packages on it. Returns a dict with at least 'system',
    'pretty' (human-readable name), and 'family'."""
    system = platform.system()
    info = {"system": system, "pretty": system, "family": None, "pkg_cmd": None}

    if system == "Windows":
        build = None
        try:
            build = sys.getwindowsversion().build
        except Exception:
            pass
        if build and build >= 22000:
            info["pretty"] = "Windows 11"
        elif build and build >= 10000:
            info["pretty"] = f"Windows 10 (build {build})"
        else:
            info["pretty"] = f"Windows {platform.release()}".strip()
        info["family"] = "windows"

    elif system == "Darwin":
        ver = platform.mac_ver()[0] or ""
        info["pretty"] = f"macOS {ver}".strip()
        info["family"] = "macos"
        info["pkg_cmd"] = "brew install python-tk"

    elif system == "Linux":
        os_release = {}
        try:
            with open("/etc/os-release", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if not line or line.startswith("#") or "=" not in line:
                        continue
                    k, v = line.split("=", 1)
                    os_release[k] = v.strip().strip('"')
        except OSError:
            pass

        distro_id = os_release.get("ID", "linux").lower()
        id_like = os_release.get("ID_LIKE", "").lower().split()
        info["pretty"] = os_release.get("PRETTY_NAME") or f"Linux ({distro_id})"
        info["distro_id"] = distro_id

        families = [distro_id] + id_like
        if any(f in families for f in ("debian", "ubuntu")):
            info["family"] = "debian"
            info["pkg_cmd"] = "sudo apt install -y python3-tk python3-pip"
        elif any(f in families for f in ("fedora", "rhel", "centos")):
            info["family"] = "fedora"
            info["pkg_cmd"] = "sudo dnf install -y python3-tkinter python3-pip"
        elif "arch" in families:
            info["family"] = "arch"
            info["pkg_cmd"] = "sudo pacman -S --needed tk python-pip"
        elif "gentoo" in families:
            info["family"] = "gentoo"
            info["pkg_cmd"] = "sudo emerge --ask dev-lang/tk dev-python/pip"
        elif any(f in families for f in ("suse", "opensuse")):
            info["family"] = "suse"
            info["pkg_cmd"] = "sudo zypper install -y python3-tk python3-pip"
        elif "alpine" in families:
            info["family"] = "alpine"
            info["pkg_cmd"] = "sudo apk add py3-tkinter py3-pip"
        else:
            info["family"] = "linux-other"
            info["pkg_cmd"] = None
    else:
        info["family"] = "unknown"

    return info


