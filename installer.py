    def browse(self):
        d = filedialog.askdirectory(initialdir=self.dir_var.get())
        if d:
            self.dir_var.set(d)

    def append_log(self, text):
        self.log.configure(state="normal")
        self.log.insert("end", text + "\n")
        self.log.configure(state="disabled")
        self.log.see("end")

    def poll_log(self):
        try:
            while True:
                line = self.log_q.get_nowait()
                if line == "__ENABLE_BUTTON__":
                    self.install_btn.configure(state="normal")
                else:
                    self.append_log(line)
        except queue.Empty:
            pass
        self.after(100, self.poll_log)

    def start_install(self):
        self.install_btn.configure(state="disabled")
        threading.Thread(target=self.do_install, daemon=True).start()

    def do_install(self):
        q = self.log_q
        target_dir = self.dir_var.get()
        family = SYSTEM_INFO["family"]
        try:
            q.put(f"Detected system: {SYSTEM_INFO['pretty']}")
            os.makedirs(target_dir, exist_ok=True)
            q.put(f"Installing to {target_dir}")

            app_path = os.path.join(target_dir, "encrypter.py")
            with open(app_path, "wb") as f:
                f.write(base64.b64decode(ENCRYPTER_PY_B64))
            q.put("Wrote encrypter.py")

            req_path = os.path.join(target_dir, "requirements.txt")
            with open(req_path, "w", encoding="utf-8") as f:
                f.write(REQUIREMENTS_TXT)
            q.put("Wrote requirements.txt")

            py = find_python()
            if not py:
                q.put("! Python was not found on PATH.")
                if family == "windows":
                    q.put("! Install Python 3.8+ from https://www.python.org/downloads/ and re-run.")
                elif family == "macos":
                    q.put("! Install Python 3.8+ from https://www.python.org/downloads/macos/")
                    q.put("! (or: brew install python) and re-run.")
                elif family in PY_INSTALL_CMDS:
                    q.put(f"! Install it with:  {PY_INSTALL_CMDS[family]}")
                    q.put("! then re-run this installer.")
                else:
                    q.put("! Install Python 3.8+ using your distro's package manager and re-run.")
                return
            q.put(f"Using Python: {py}")

            rc = run_logged([py, "-c", "import sys; sys.exit(0 if sys.version_info >= (3, 8) else 1)"], q)
            if rc != 0:
                q.put("! Python 3.8+ is required.")
                return

            rc = run_logged([py, "-c", "import tkinter"], q)
            if rc != 0:
                q.put("! tkinter is missing from this Python install.")
                if family == "windows":
                    q.put('! Reinstall Python with "tcl/tk and IDLE" checked.')
                elif SYSTEM_INFO.get("pkg_cmd"):
                    q.put(f"! Install it with:  {SYSTEM_INFO['pkg_cmd']}")
                else:
                    q.put("! Install the Tk/tkinter package for your distro (often 'python3-tk' or 'tk').")
                return

            with open(req_path, "r", encoding="utf-8") as f:
                real_reqs = [l for l in f if l.strip() and not l.strip().startswith("#")]
            if real_reqs:
                q.put("Installing dependencies from requirements.txt (cryptography, etc.) ...")
                run_logged([py, "-m", "pip", "install", "-r", req_path], q)
            else:
                q.put("No extra packages required.")

            exe_path = None
            if self.build_exe_var.get():
                q.put("Installing PyInstaller ...")
                run_logged([py, "-m", "pip", "install", "--upgrade", "pyinstaller"], q)
                q.put("Building the Encrypter executable (this can take a minute) ...")
                dist_dir = os.path.join(target_dir, "dist")
                build_dir = os.path.join(target_dir, "build")
                cmd = [py, "-m", "PyInstaller", "--onefile", "--name", "Encrypter",
                       "--distpath", dist_dir, "--workpath", build_dir, "--specpath", build_dir]
                if family in ("windows", "macos"):
                    cmd.append("--noconsole")
                cmd.append(app_path)
                run_logged(cmd, q)
                candidate = os.path.join(dist_dir, "Encrypter.exe" if family == "windows" else "Encrypter")
                if os.path.exists(candidate):
                    exe_path = candidate
                    q.put(f"Built: {exe_path}")
                else:
                    q.put("! Build did not produce an executable -- see log above.")

            if self.shortcut_var.get():
                if family == "windows":
                    ps1_path = os.path.join(target_dir, "create_shortcut.ps1")
                    with open(ps1_path, "w", encoding="utf-8") as f:
                        f.write(CREATE_SHORTCUT_PS1)
                    if exe_path:
                        cmd = ["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", ps1_path,
                               "-Target", exe_path, "-WorkingDirectory", target_dir]
                    else:
                        pyw = shutil.which("pythonw") or py
                        cmd = ["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", ps1_path,
                               "-Target", pyw, "-Arguments", app_path, "-WorkingDirectory", target_dir]
                    run_logged(cmd, q)

                elif family == "macos":
                    exec_cmd = f'"{exe_path}"' if exe_path else f'"{py}" "{app_path}"'
                    launcher = MACOS_LAUNCHER_COMMAND.format(workdir=target_dir, exec_cmd=exec_cmd)
                    desktop_path = os.path.join(os.path.expanduser("~"), "Desktop", "Encrypter.command")
                    try:
                        with open(desktop_path, "w", encoding="utf-8") as f:
                            f.write(launcher)
                        os.chmod(desktop_path, 0o755)
                        q.put(f"Created launcher: {desktop_path}")
                        q.put("Note: the first time you double-click it, macOS Gatekeeper may require")
                        q.put("right-click -> Open once, since it isn't a signed/notarized app.")
                    except OSError as e:
                        q.put(f"! Could not create Desktop launcher: {e}")

                else:  # Linux and other Unix-like systems
                    exec_cmd = f'"{exe_path}"' if exe_path else f'"{py}" "{app_path}"'
                    entry = LINUX_DESKTOP_ENTRY.format(workdir=target_dir, exec_cmd=exec_cmd)
                    apps_dir = os.path.join(os.path.expanduser("~"), ".local", "share", "applications")
                    try:
                        os.makedirs(apps_dir, exist_ok=True)
                        entry_path = os.path.join(apps_dir, "encrypter.desktop")
                        with open(entry_path, "w", encoding="utf-8") as f:
                            f.write(entry)
                        os.chmod(entry_path, 0o755)
                        q.put(f"Created application menu entry: {entry_path}")
                    except OSError as e:
                        q.put(f"! Could not create application menu entry: {e}")

                    desktop_dir = os.path.join(os.path.expanduser("~"), "Desktop")
                    if os.path.isdir(desktop_dir):
                        try:
                            desktop_copy = os.path.join(desktop_dir, "Encrypter.desktop")
                            with open(desktop_copy, "w", encoding="utf-8") as f:
                                f.write(entry)
                            os.chmod(desktop_copy, 0o755)
                            q.put(f"Created Desktop shortcut: {desktop_copy}")
                            q.put("Note: some desktop environments require right-click -> 'Allow Launching'")
                            q.put("the first time you use a new .desktop file.")
                        except OSError as e:
                            q.put(f"! Could not create Desktop shortcut: {e}")

            q.put("")
            q.put("Done.")
            if exe_path:
                q.put(f"Run: {exe_path}")
            else:
                q.put(f'Run: {py} "{app_path}"')
        except Exception as e:
            q.put(f"! Unexpected error: {e}")
        finally:
            q.put("__ENABLE_BUTTON__")


