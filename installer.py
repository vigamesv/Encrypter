def apply_dark_titlebar(window):
    """Windows-only cosmetic touch; no-op elsewhere (macOS follows the system
    appearance automatically, and most Linux window managers don't expose an
    equivalent per-window API)."""
    if sys.platform != "win32":
        return
    try:
        window.update_idletasks()
        hwnd = ctypes.windll.user32.GetParent(window.winfo_id())
        dwmapi = ctypes.windll.dwmapi
        value = ctypes.c_int(1)
        for attr in (20, 19):
            hr = dwmapi.DwmSetWindowAttribute(hwnd, attr, ctypes.byref(value), ctypes.sizeof(value))
            if hr == 0:
                break
    except Exception:
        pass


import ctypes


def find_python():
    candidates = ("py", "python3", "python") if sys.platform == "win32" else ("python3", "python")
    for candidate in candidates:
        p = shutil.which(candidate)
        if p:
            return p
    return None


def default_install_dir(sysinfo):
    if sysinfo["family"] == "windows":
        base = os.environ.get("LOCALAPPDATA", os.path.expanduser("~"))
        return os.path.join(base, "Programs", "Encrypter")
    if sysinfo["family"] == "macos":
        return os.path.join(os.path.expanduser("~"), "Applications", "Encrypter")
    return os.path.join(os.path.expanduser("~"), ".local", "share", "Encrypter")


def run_logged(cmd, log_q, cwd=None):
    log_q.put("$ " + " ".join(cmd))
    try:
        kwargs = {}
        if sys.platform == "win32":
            kwargs["creationflags"] = subprocess.CREATE_NO_WINDOW
        proc = subprocess.Popen(
            cmd, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
            text=True, **kwargs,
        )
    except Exception as e:
        log_q.put(f"! failed to start: {e}")
        return 1
    for line in proc.stdout:
        log_q.put(line.rstrip())
    proc.wait()
    return proc.returncode


